test('desktop and mobile private QR upload workflow', async ({ browser }) => {
  const context = await browser.newContext({baseURL:'http://127.0.0.1:5173',viewport:{width:1440,height:900}});
  const page = await context.newPage();
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'PrintSetu',exact:true})).toBeVisible();
  await expect(page.locator('.hero')).toHaveCSS('background-image',/print-station/);
  await page.screenshot({path:'test-results/landing-desktop.png',fullPage:true});
  await page.goto('/register');
  await page.getByLabel('Your name').fill('Browser Test Owner');
  await page.getByLabel('Shop name').fill('Browser Test Shop');
  const email = 'browser-' + Date.now() + '@example.com';
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password',{exact:true}).fill('BrowserTest123!');
  const registration = page.waitForResponse(r=>r.url().endsWith('/api/auth/register'));
  await page.getByRole('button',{name:'Create shop',exact:true}).click();
  const registrationBody = await (await registration).json();
  expect(registrationBody.development_code).toMatch(/^\d{6}$/);
  await page.getByLabel('Email verification code').fill(registrationBody.development_code);
  await page.getByRole('button',{name:'Verify email',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Browser Test Shop',exact:true,level:1})).toBeVisible();
  await expect(page.getByAltText('Shop customer QR code')).toBeVisible();
  await page.screenshot({path:'test-results/owner-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Connect computer',exact:true}).first().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog')).not.toContainText('python');
  const code = await page.locator('.code-row strong').innerText();
  const activated = await context.request.post('/api/agent/activate',{data:{code,name:'Browser mock connector'}});
  expect(activated.status()).toBe(200);
  const device = await activated.json();
  const headers = {Authorization:'Bearer '+device.credential};
  expect((await context.request.post('/api/agent/connection',{headers,data:{mode:'mock'}})).status()).toBe(200);
  await page.getByRole('button',{name:'Done',exact:true}).click();
  const summary = await (await context.request.get('/api/owner/summary')).json();
  const shop = summary.shops[0];
  const mobile = await browser.newContext({baseURL:'http://127.0.0.1:5173',viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const customer = await mobile.newPage();
  customer.on('pageerror', e=>errors.push(e.message));
  await customer.goto('/shop/'+shop.slug);
  await expect(customer.getByRole('heading',{name:'Browser Test Shop',exact:true})).toBeVisible();
  await customer.getByLabel('Choose PDF').setInputFiles({name:'browser-check.pdf',mimeType:'application/pdf',buffer:pdf});
  await expect(customer.getByText('Uploaded',{exact:true})).toBeVisible();
  await expect(customer.getByRole('button',{name:'Submit demo print job'})).toBeEnabled();
  await expect(customer.locator('.estimate strong')).toContainText('2.00');
  await expect(customer.getByAltText('Document page 1')).toBeVisible();
  await expect.poll(()=>customer.getByAltText('Document page 1').evaluate((img: HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(0);
  expect(await customer.evaluate(()=>innerWidth)).toBe(390);
  expect(await customer.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await customer.screenshot({path:'test-results/customer-mobile.png',fullPage:true});
  const submitted=customer.waitForResponse(r=>r.url().endsWith('/orders') && r.request().method()==='POST');
  await customer.getByRole('button',{name:'Submit demo print job'}).click();
  const order=await (await submitted).json();
  const job=await (await context.request.get('/api/agent/jobs/next',{headers})).json();
  expect(job.job.id).toBeTruthy();
  for(const status of ['PRINTING','COMPLETED']) expect((await context.request.post('/api/agent/jobs/'+job.job.id+'/status',{headers,data:{status,adapter_mode:'mock'}})).status()).toBe(200);
  await expect(customer.getByText('Mock mode - no physical printing')).toBeVisible();
  await expect(customer.locator('.receipt-status strong')).toHaveText('completed');
  const download=customer.waitForEvent('download');
  await customer.getByRole('link',{name:'Download receipt'}).click();
  expect((await download).suggestedFilename()).toContain(order.order_number);
  expect(errors).toEqual([]);
  await mobile.close(); await context.close();
});

